    // Dispatch is a static (built once, shared across every scope) Dictionary<Type, Func<...>>
    // rather than `switch (request) { case T1: ... case T2: ... }`, so a compilation with many
    // handlers still gets O(1) hash lookup instead of O(n) sequential type tests.

    private static void AppendSendAsync(StringBuilder sb, ImmutableArray<HandlerModel> models)
    {
        sb.AppendLine("        private static readonly global::System.Collections.Generic.Dictionary<");
        sb.AppendLine("            global::System.Type,");
        sb.AppendLine("            global::System.Func<global::System.IServiceProvider, global::Davish.Sendr.IRequest, " +
                      "global::System.Threading.CancellationToken, global::System.Threading.Tasks.Task>> _requestHandlers = new()");
        sb.AppendLine("        {");

        foreach (var model in models)
        {
            sb.AppendLine($"            [typeof({model.RequestType})] = static (sp, request, cancellationToken) =>");
            sb.AppendLine("            {");
            sb.AppendLine($"                var r = ({model.RequestType})request;");
            sb.AppendLine($"                var h = (global::Davish.Sendr.IRequestHandler<{model.RequestType}>)" +
                           $"sp.GetRequiredService<{model.HandlerType}>();");
            AppendDecoratorLocals(sb, model, "global::Davish.Sendr.IRequestDecorator");
            var call = BuildComposedCall(model, "h.HandleAsync(r, cancellationToken)");
            sb.AppendLine($"                return {call};");
            sb.AppendLine("            },");
        }

        sb.AppendLine("        };");
        sb.AppendLine();
        sb.AppendLine("        public global::System.Threading.Tasks.Task SendAsync(");
        sb.AppendLine("            global::Davish.Sendr.IRequest request,");
        sb.AppendLine("            global::System.Threading.CancellationToken cancellationToken)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (_requestHandlers.TryGetValue(request.GetType(), out var handler))");
        sb.AppendLine("                return handler(_sp, request, cancellationToken);");
        sb.AppendLine();
        sb.AppendLine("            throw new global::System.InvalidOperationException(");
        sb.AppendLine("                $\"Davish.Sendr: no IRequestHandler<{request.GetType()}> is registered.\");");
        sb.AppendLine("        }");
    }

    private static void AppendSendAsyncWithResponse(StringBuilder sb, ImmutableArray<HandlerModel> models)
    {
        sb.AppendLine("        private static readonly global::System.Collections.Generic.Dictionary<");
        sb.AppendLine("            global::System.Type,");
        sb.AppendLine("            global::System.Func<global::System.IServiceProvider, global::Davish.Sendr.IRequest, " +
                      "global::System.Threading.CancellationToken, global::System.Threading.Tasks.Task>> _requestResponseHandlers = new()");
        sb.AppendLine("        {");

        foreach (var model in models)
        {
            sb.AppendLine($"            [typeof({model.RequestType})] = static (sp, request, cancellationToken) =>");
            sb.AppendLine("            {");
            sb.AppendLine($"                var r = ({model.RequestType})request;");
            sb.AppendLine($"                var h = (global::Davish.Sendr.IRequestHandler<{model.RequestType}, {model.ResponseType}>)" +
                           $"sp.GetRequiredService<{model.HandlerType}>();");
            AppendDecoratorLocals(sb, model, "global::Davish.Sendr.IRequestDecorator.WithResponse");
            var call = BuildComposedCall(model, "h.HandleAsync(r, cancellationToken)");
            sb.AppendLine($"                return {call};"); // Task<{ResponseType}> is-a Task, no cast needed here.
            sb.AppendLine("            },");
        }

        sb.AppendLine("        };");
        sb.AppendLine();
        sb.AppendLine("        public global::System.Threading.Tasks.Task<TResponse> SendAsync<TResponse>(");
        sb.AppendLine("            global::Davish.Sendr.IRequest<TResponse> request,");
        sb.AppendLine("            global::System.Threading.CancellationToken cancellationToken)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (_requestResponseHandlers.TryGetValue(request.GetType(), out var handler))");
        sb.AppendLine("                return (global::System.Threading.Tasks.Task<TResponse>)handler(_sp, request, cancellationToken);");
        sb.AppendLine();
        sb.AppendLine("            throw new global::System.InvalidOperationException(");
        sb.AppendLine("                $\"Davish.Sendr: no IRequestHandler<{request.GetType()}, {typeof(TResponse)}> is registered.\");");
        sb.AppendLine("        }");
    }

    private static void AppendSendStream(StringBuilder sb, ImmutableArray<HandlerModel> models)
    {
        sb.AppendLine("        private static readonly global::System.Collections.Generic.Dictionary<");
        sb.AppendLine("            global::System.Type,");
        sb.AppendLine("            global::System.Func<global::System.IServiceProvider, object, " +
                      "global::System.Threading.CancellationToken, object>> _streamHandlers = new()");
        sb.AppendLine("        {");

        foreach (var model in models)
        {
            sb.AppendLine($"            [typeof({model.RequestType})] = static (sp, request, cancellationToken) =>");
            sb.AppendLine("            {");
            sb.AppendLine($"                var r = ({model.RequestType})request;");
            sb.AppendLine($"                var h = (global::Davish.Sendr.IStreamRequestHandler<{model.RequestType}, {model.ResponseType}>)" +
                           $"sp.GetRequiredService<{model.HandlerType}>();");
            AppendDecoratorLocals(sb, model, "global::Davish.Sendr.IStreamRequestDecorator");
            var call = BuildComposedCall(model, "h.HandleAsync(r, cancellationToken)");
            sb.AppendLine($"                return {call};"); // IAsyncEnumerable<{ResponseType}> is a reference type, boxed as object here.
            sb.AppendLine("            },");
        }

        sb.AppendLine("        };");
        sb.AppendLine();
        sb.AppendLine("        public global::System.Collections.Generic.IAsyncEnumerable<TResponse> SendStream<TResponse>(");
        sb.AppendLine("            global::Davish.Sendr.IStreamRequest<TResponse> request,");
        sb.AppendLine("            global::System.Threading.CancellationToken cancellationToken)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (_streamHandlers.TryGetValue(request.GetType(), out var handler))");
        sb.AppendLine("                return (global::System.Collections.Generic.IAsyncEnumerable<TResponse>)handler(_sp, request, cancellationToken);");
        sb.AppendLine();
        sb.AppendLine("            throw new global::System.InvalidOperationException(");
        sb.AppendLine("                $\"Davish.Sendr: no IStreamRequestHandler<{request.GetType()}, {typeof(TResponse)}> is registered.\");");
        sb.AppendLine("        }");
    }

    private static void AppendDecoratorLocals(StringBuilder sb, HandlerModel model, string decoratorInterface)
    {
        for (var i = 0; i < model.Decorators.Length; i++)
        {
            sb.AppendLine($"                var d{i} = ({decoratorInterface})" +
                           $"sp.GetRequiredService<{model.Decorators[i].TypeName}>();");
        }
    }

    /// <summary>
    /// Wraps <paramref name="innermostCall"/> with the model's decorators, outermost-first,
    /// mirroring the ordering of <c>x.Decorator.With&lt;T&gt;()</c> chains: the first
    /// <c>[Decorate]</c> declared is the outermost layer and runs first.
    /// </summary>
    private static string BuildComposedCall(HandlerModel model, string innermostCall)
    {
        var call = innermostCall;
        for (var i = model.Decorators.Length - 1; i >= 0; i--)
            call = $"d{i}.HandleAsync(r, () => {call}, cancellationToken)";
        return call;
    }
}
