using System.Text;

namespace Davish.Sendr.Generators;

/// <summary>
/// Renders the <c>GeneratedSender</c> class and the <c>UseGenerators()</c> registration method
/// as plain C# text.
/// </summary>
internal static class SourceBuilder
{
    public static string Build(ImmutableArray<HandlerModel> models)
    {
