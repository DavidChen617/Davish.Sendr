    // Unlike every other handler kind, a notification type is expected to have any number of
    // handlers (including zero), so these are grouped by notification type into a
    // Dictionary<Type, Func<...>[]> rather than a Dictionary<Type, Func<...>> of exactly one.
    private static void AppendGeneratedPublisher(StringBuilder sb, ImmutableArray<HandlerModel> models)
    {
        sb.AppendLine("    internal sealed class GeneratedPublisher : global::Davish.Sendr.IPublisher");
        sb.AppendLine("    {");
        sb.AppendLine("        private readonly global::System.IServiceProvider _sp;");
        sb.AppendLine("        private readonly global::Davish.Sendr.NotificationRunMode _runMode;");
        sb.AppendLine();
        sb.AppendLine("        public GeneratedPublisher(global::System.IServiceProvider sp, global::Davish.Sendr.NotificationRunMode runMode)");
        sb.AppendLine("        {");
        sb.AppendLine("            _sp = sp;");
        sb.AppendLine("            _runMode = runMode;");
        sb.AppendLine("        }");
        sb.AppendLine();

        sb.AppendLine("        private static readonly global::System.Collections.Generic.Dictionary<");
        sb.AppendLine("            global::System.Type,");
        sb.AppendLine("            global::System.Func<global::System.IServiceProvider, global::Davish.Sendr.INotification, " +
                      "global::System.Threading.CancellationToken, global::System.Threading.Tasks.Task>[]> _notificationHandlers = new()");
        sb.AppendLine("        {");

        foreach (var group in models.GroupBy(m => m.RequestType))
        {
            sb.AppendLine($"            [typeof({group.Key})] = new global::System.Func<global::System.IServiceProvider, " +
                          "global::Davish.Sendr.INotification, global::System.Threading.CancellationToken, " +
                          "global::System.Threading.Tasks.Task>[]");
            sb.AppendLine("            {");

            foreach (var model in group)
            {
                sb.AppendLine("                static (sp, notification, cancellationToken) =>");
                sb.AppendLine("                {");
                sb.AppendLine($"                    var r = ({model.RequestType})notification;");
                sb.AppendLine($"                    var h = (global::Davish.Sendr.INotificationHandler<{model.RequestType}>)" +
                               $"sp.GetRequiredService<{model.HandlerType}>();");
                AppendDecoratorLocals(sb, model, "global::Davish.Sendr.INotificationDecorator");
                var call = BuildComposedCall(model, "h.HandleAsync(r, cancellationToken)");
                sb.AppendLine($"                    return {call};");
                sb.AppendLine("                },");
            }

            sb.AppendLine("            },");
        }

        sb.AppendLine("        };");
        sb.AppendLine();

        sb.AppendLine("        public global::System.Threading.Tasks.Task PublishAsync(");
        sb.AppendLine("            global::Davish.Sendr.INotification notification,");
        sb.AppendLine("            global::System.Threading.CancellationToken cancellationToken)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (notification is null)");
        sb.AppendLine("                throw new global::System.ArgumentNullException(nameof(notification));");
        sb.AppendLine();
        sb.AppendLine("            if (!_notificationHandlers.TryGetValue(notification.GetType(), out var steps))");
        sb.AppendLine("                return global::System.Threading.Tasks.Task.CompletedTask;");
        sb.AppendLine();
        sb.AppendLine("            var bound = new global::System.Func<global::System.Threading.CancellationToken, " +
                      "global::System.Threading.Tasks.Task>[steps.Length];");
        sb.AppendLine("            for (var i = 0; i < steps.Length; i++)");
        sb.AppendLine("            {");
        sb.AppendLine("                var step = steps[i];");
        sb.AppendLine("                bound[i] = ct => step(_sp, notification, ct);");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.AppendLine("            return _runMode == global::Davish.Sendr.NotificationRunMode.Parallel");
        sb.AppendLine("                ? global::Davish.Sendr.NotificationGroupRunner.RunParallelAsync(bound, cancellationToken)");
        sb.AppendLine("                : global::Davish.Sendr.NotificationGroupRunner.RunSequenceAsync(bound, cancellationToken);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

