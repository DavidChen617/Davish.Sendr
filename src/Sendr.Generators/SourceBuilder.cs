        sb.AppendLine();
        sb.AppendLine("        public GeneratedSender(global::System.IServiceProvider sp) => _sp = sp;");
        sb.AppendLine();

        AppendSendAsync(sb, models.Where(m => m.Kind == HandlerKind.Request).ToImmutableArray());
        sb.AppendLine();
        AppendSendAsyncWithResponse(sb, models.Where(m => m.Kind == HandlerKind.RequestResponse).ToImmutableArray());
        sb.AppendLine();
