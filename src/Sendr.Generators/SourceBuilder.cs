        sb.AppendLine("        /// (and <c>[Decorate&lt;...&gt;]</c> pipeline) discovered in this compilation. Every");
        sb.AppendLine("        /// notification type may have any number of handlers; among handlers of the same");
        sb.AppendLine("        /// notification, no ordering is guaranteed. Call from <c>AddSendrNotification</c>:");
        sb.AppendLine("        /// <c>services.AddSendrNotification(o =&gt; o.UseGenerators())</c>.");
        sb.AppendLine("        /// </summary>");
        sb.AppendLine("        /// <param name=\"options\">The options being configured.</param>");
        sb.AppendLine("        /// <param name=\"configure\">");
        sb.AppendLine("        /// An optional callback to choose how handlers of the same notification run relative to");
        sb.AppendLine("        /// each other, via <c>x.RunAs(NotificationRunMode.Parallel)</c>. Defaults to");
        sb.AppendLine("        /// <see cref=\"global::Davish.Sendr.NotificationRunMode.Sequence\"/>.");
        sb.AppendLine("        /// </param>");
        sb.AppendLine("        public static global::Davish.Sendr.NotificationOptions UseGenerators(");
        sb.AppendLine("            this global::Davish.Sendr.NotificationOptions options,");
        sb.AppendLine("            global::System.Action<global::Davish.Sendr.GeneratedNotificationRunOptions>? configure = null)");
        sb.AppendLine("        {");
        sb.AppendLine("            var runOptions = new global::Davish.Sendr.GeneratedNotificationRunOptions();");
        sb.AppendLine("            configure?.Invoke(runOptions);");
        sb.AppendLine();
        sb.AppendLine("            options.UsePublisher<global::Davish.Sendr.Generated.GeneratedPublisher>();");
        sb.AppendLine("            var services = options.Services;");
        sb.AppendLine("            services.AddSingleton(typeof(global::Davish.Sendr.NotificationRunMode), runOptions.RunMode);");
        sb.AppendLine();

        AppendHandlerAndDecoratorRegistrations(sb, models);

        sb.AppendLine();
        sb.AppendLine("            return options;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

    private static void AppendDecoratorLocals(StringBuilder sb, HandlerModel model, string decoratorInterface)
    {
        for (var i = 0; i < model.Decorators.Length; i++)
        {
            sb.AppendLine($"                var d{i} = ({decoratorInterface})" +
                           $"sp.GetRequiredService<{model.Decorators[i].TypeName}>();");
        }
    }

    /// <summary>
    /// Wraps <paramref name="innermostCall"/> with the model's decorators, outermost-first,
    /// mirroring the ordering of <c>x.Decorator.With&lt;T&gt;()</c> chains: the first
    /// <c>[Decorate]</c> declared is the outermost layer and runs first.
    /// </summary>
    private static string BuildComposedCall(HandlerModel model, string innermostCall)
    {
        var call = innermostCall;
        for (var i = model.Decorators.Length - 1; i >= 0; i--)
            call = $"d{i}.HandleAsync(r, () => {call}, cancellationToken)";
        return call;
    }
